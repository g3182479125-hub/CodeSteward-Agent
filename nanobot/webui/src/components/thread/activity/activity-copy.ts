const PREFIX_COPY: Array<[string, string]> = [
  ["正在执行工具 ", "Running "],
  ["工具执行完成 ", "Completed "],
  ["工具执行失败 ", "Could not complete "],
  ["搜索失败 ", "Could not search "],
  ["正在搜索 ", "Searching "],
  ["已搜索 ", "Searched "],
  ["在 ", "in "],
  ["无法使用 ", "Could not use "],
  ["正在使用 ", "Using "],
  ["已使用 ", "Used "],
];

/** Activity models are pure functions, so they cannot use React's `t` hook. */
export function localizeActivityText(value: string): string {
  if (currentLocale() === "zh-CN") return value;
  const exact = EXACT_COPY[value];
  if (exact) return exact;
  for (const [chinesePrefix, englishPrefix] of PREFIX_COPY) {
    if (value.startsWith(chinesePrefix)) {
      return `${englishPrefix}${value.slice(chinesePrefix.length)}`;
    }
  }
  const countMatch = /^(\d+) 个文件$/.exec(value);
  if (countMatch) return `${countMatch[1]} files`;
  const searchCountMatch = /^(\d+) 次搜索$/.exec(value);
  if (searchCountMatch) return `${searchCountMatch[1]} searches`;
  const actionCountMatch = /^(\d+) 个动作$/.exec(value);
  if (actionCountMatch) return `${actionCountMatch[1]} actions`;
  const scriptMatch = / · 脚本，共 (\d+) 行$/.exec(value);
  if (scriptMatch) return value.replace(scriptMatch[0], ` · script, ${scriptMatch[1]} lines`);
  return value;
}
